import { chromium } from "playwright";
const EXE = process.env.HOME + "/Library/Caches/ms-playwright/chromium_headless_shell-1244/chrome-headless-shell-mac-arm64/chrome-headless-shell";
const url = "https://prysmnote.com/cookie-policy";
const browser = await chromium.launch({ executablePath: EXE });
const ctxNoJs = await browser.newContext({ viewport: { width: 412, height: 900 }, javaScriptEnabled: false });
const p1 = await ctxNoJs.newPage();
await p1.goto(url, { waitUntil: "load", timeout: 45000 });
const ssr = (await p1.evaluate(() => document.body.innerText)).replace(/\s+/g, " ").trim();
await browser.close();
const b2 = await chromium.launch({ executablePath: EXE });
const ctx = await b2.newContext({ viewport: { width: 412, height: 900 } });
const p2 = await ctx.newPage();
await p2.goto(url, { waitUntil: "load", timeout: 45000 });
await p2.waitForTimeout(2500);
const hyd = (await p2.evaluate(() => document.body.innerText)).replace(/\s+/g, " ").trim();
await b2.close();
const a = ssr.split(" "), b = hyd.split(" ");
let i = 0;
while (i < a.length && i < b.length && a[i] === b[i]) i++;
console.log("first diff at word", i);
console.log("SSR :", a.slice(Math.max(0, i - 12), i + 12).join(" "));
console.log("HYD :", b.slice(Math.max(0, i - 12), i + 12).join(" "));
